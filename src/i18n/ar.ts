const dictionary: Record<string, string> = ar;

/** النص بتاع الـ key، أو اسم الـ key نفسه لو لسه فاضي. */
export function t(key: string): string {
	if (!(key in dictionary)) throw new Error(`Unknown text key: ${key}`);
	return dictionary[key].trim() || key;
}

/** النص بتاع الـ key، أو undefined لو فاضي. للـ Schema عشان أسماء الـ keys ما توصلش لجوجل. */
export function filled(key: string): string | undefined {
	return dictionary[key]?.trim() || undefined;
}

/** عناصر قايمة: items('services.items') ← ['services.items.1', 'services.items.2', ...] */
export function items(prefix: string): string[] {
	const ids = new Set<string>();
	for (const key of Object.keys(dictionary)) {
		if (key.startsWith(`${prefix}.`)) ids.add(key.slice(prefix.length + 1).split('.')[0]);
	}
	return [...ids].map((id) => `${prefix}.${id}`);
}

/** كل الـ keys اللي لسه فاضية. */
export function missingKeys(): string[] {
	return Object.keys(dictionary).filter((key) => !dictionary[key].trim());
}
